# Pedir dos números decimales y mostrar
# la suma, resta, multiplicación y división.

a = float(input("Ingresa el valor de a: "))
b = float(input("Ingresa el valor de b: "))

print("Suma:", a + b)
print("Resta:", a - b)
print("Multiplicación:", a * b)
print("División:", a / b)

